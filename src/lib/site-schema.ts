import { z } from 'astro/zod';

/** 后台清空可选链接时会写成空字符串，这里统一按「未填」处理 */
const optionalUrl = z.preprocess(
  (value) => (value === null || value === undefined ? '' : value),
  z.string().refine((value) => value === '' || /^https?:\/\/\S+$/.test(value), {
    message: '必须是 http(s) 链接',
  }),
);

const text = z.string().min(1);
/** 模板文案必须保留占位符，避免后台编辑时误删导致替换失效 */
const template = (...placeholders: string[]) =>
  text.refine((value) => placeholders.every((placeholder) => value.includes(placeholder)), {
    message: `需包含 ${placeholders.join('、')} 占位符`,
  });

/**
 * 后台 list 控件会把没填的空行一起保存成 ""：
 * 先剔除空白项再校验，避免一次误操作让整站构建失败。
 */
const copyList = () =>
  z.preprocess(
    (value) =>
      Array.isArray(value)
        ? value
            .filter((item): item is string => typeof item === 'string')
            .map((item) => item.trim())
            .filter((item) => item !== '')
        : value,
    z.array(text),
  );

const MONTH_FALLBACK = [
  '一月', '二月', '三月', '四月', '五月', '六月',
  '七月', '八月', '九月', '十月', '十一月', '十二月',
];

/** 归档月份固定 12 项：空行按索引回落到默认月份名，保证月份与文案不错位 */
const monthLabels = z.preprocess((value) => {
  const list = Array.isArray(value) ? value : [];
  return MONTH_FALLBACK.map((fallback, index) => {
    const item = list[index];
    const label = typeof item === 'string' ? item.trim() : '';
    return label || fallback;
  });
}, z.array(text).length(12));

